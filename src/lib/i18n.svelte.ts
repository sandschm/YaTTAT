const dictionaries: Record<Lang, Record<Key, string>> = { de, en };

function systemLang(): Lang {
  const nav = typeof navigator !== "undefined" ? navigator.language : "";
  return nav.toLowerCase().startsWith("de") ? "de" : "en";
}

export function resolveLanguage(setting: LanguageSetting | undefined): Lang {
  if (setting === "de" || setting === "en") return setting;
  return systemLang();
}

class I18n {
  lang = $state<Lang>(systemLang());
  /** BCP 47 locale for date and number formatting. */
  locale = $derived(this.lang === "de" ? "de-DE" : "en-US");
}

export const i18n = new I18n();

/** Translates `key`, replacing `{name}` placeholders with `params`. */
export function t(key: Key, params?: Record<string, string | number>): string {
  let text: string = dictionaries[i18n.lang][key] ?? de[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) text = text.split(`{${k}}`).join(String(v));
  }
  return text;
}
